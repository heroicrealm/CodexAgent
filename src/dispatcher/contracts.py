"""Public structural contracts for the V2 components implemented in Stage B."""
from typing import Protocol
from collections.abc import Callable, Mapping
from contextlib import AbstractContextManager
import sqlite3
from .config import Project
from .models import (ApprovedSnapshot, Eligibility, Execution, ExecutionResult,
    InputComment, IssueObservation, ObservationBatch, PRObservation, PublishResult, State, SyncResult)


class Runtime(Protocol):
    def run(self, *, once: bool = False) -> None: ...
    def stop(self, force: bool = False) -> None: ...


class GitHubAdapter(Protocol):
    def issues(self, project: Project, poll_id: str) -> tuple[IssueObservation, ...]: ...
    def issue(self, project: Project, number: int, poll_id: str | None = None) -> IssueObservation: ...
    def parent(self, project: Project, number: int, poll_id: str) -> IssueObservation | None: ...
    def children(self, project: Project, number: int, poll_id: str) -> tuple[IssueObservation, ...]: ...
    def input_comment(self, project: Project, number: int, poll_id: str | None = None) -> InputComment | None: ...
    def pr(self, project: Project, number: int, issue_id: int, poll_id: str | None = None) -> PRObservation: ...
    def find_pr(self, project: Project, branch: str, issue_id: int, poll_id: str | None = None, *,
                since: str | None = None, excluded: frozenset[int] = frozenset()) -> PRObservation | None: ...
    def output(self, project: Project, issue: sqlite3.Row, body: str) -> tuple[int, str]: ...
    def create_pr(self, project: Project, issue: sqlite3.Row, branch: str, base: str) -> PRObservation: ...
    def sync_labels(self, project: Project, number: int, state: str,
                    observed: frozenset[str] | None = None, poll_id: str | None = None) -> None: ...
    def close_issue(self, project: Project, number: int, state: str) -> None: ...


class PollService(Protocol):
    def poll_project(self, project: Project) -> SyncResult: ...


class StateService(Protocol):
    def apply_observation(self, project: Project, batch: ObservationBatch) -> SyncResult: ...
    def approve(self, project: Project, issue: IssueObservation, comment: InputComment | None,
                source: IssueObservation | None = None) -> bool: ...
    def apply_pr(self, pr: PRObservation, *, recover: bool = False) -> None: ...
    def transition(self, issue_id: int, expected_state: State, target_state: State, reason: str) -> bool: ...


class GroupService(Protocol):
    def evaluate(self, issue_id: int) -> Eligibility: ...


class Scheduler(Protocol):
    def reserve(self, issue_id: int) -> Execution | None: ...


class Executor(Protocol):
    def prepare(self, execution_id: int) -> Execution: ...
    def run_once(self, execution_id: int) -> ExecutionResult: ...


class Publisher(Protocol):
    def publish(self, execution_id: int) -> PublishResult: ...
    def send_final_error_report(self, issue_id: int) -> bool: ...


class Storage(Protocol):
    def transaction(self) -> AbstractContextManager[sqlite3.Connection]: ...
    def issue(self, issue_id: int) -> sqlite3.Row | None: ...
    def register_issue(self, issue: IssueObservation, project_id: str, correction_of: int | None = None) -> None: ...
    def register_child(self, child: IssueObservation, parent: IssueObservation, project_id: str,
                       correction_of: int | None = None) -> None: ...
    def transition(self, issue_id: int, expected: State, target: State, reason: str) -> bool: ...
    def commit_approval(self, issue_id: int, snapshot: ApprovedSnapshot, target: State, *,
                        correction_of: int | None = None, branches: tuple[str, str] | None = None,
                        readiness: Callable[[sqlite3.Connection], bool] | None = None) -> bool: ...
    def record_confirmed_output(self, issue_id: int, comment_id: int, body: str) -> None: ...
    def reserve(self, issue_id: int) -> Execution | None: ...
    def group_branches(self, issue_id: int) -> tuple[str | None, str | None]: ...
    def set_group_branches(self, issue_id: int, base_branch: str, work_branch: str) -> None: ...
    def mark_codex_started(self, execution_id: int) -> bool: ...
    def record_pr(self, pr: PRObservation) -> None: ...
    def record_error(self, issue_id: int, code: str, stage: str, safe_message: str,
                     execution_id: int | None = None) -> None: ...


class DiagnosticLogger(Protocol):
    def record(self, level: str, component: str, operation: str,
               context: Mapping[str, object], result: str) -> None: ...
